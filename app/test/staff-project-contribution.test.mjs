import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createWorkspace} from '../server.mjs';

const origin='http://127.0.0.1:4320';
test('owner grants and revokes project-specific studio contribution without financial or approval access',async()=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'caleane-staff-project-'));
 const {server,db}=await createWorkspace({dbFile:path.join(dir,'workspace.sqlite'),origin,demo:true});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const base=`http://127.0.0.1:${server.address().port}`,cookies={};
 async function call(route,method='GET',body,actor=''){
  const response=await fetch(base+route,{method,headers:{Origin:origin,...(body!==undefined?{'Content-Type':'application/json'}:{}),...(cookies[actor]?{Cookie:cookies[actor]}:{})},body:body!==undefined?JSON.stringify(body):undefined});
  const cookie=response.headers.get('set-cookie');if(cookie&&actor)cookies[actor]=cookie.split(';')[0];
  return {status:response.status,data:response.headers.get('content-type')?.includes('application/json')?await response.json():await response.arrayBuffer()};
 }
 try{
  assert.equal((await call('/api/login','POST',{email:'studio@example.test',password:'StudioDemo2026!'},'owner')).status,200);
  assert.equal((await call('/api/login','POST',{email:'amelia@example.test',password:'StudioDemo2026!'},'client')).status,200);
  const studio=(await call('/api/me','GET',undefined,'owner')).data.studios[0].id,q=`?studio=${studio}`;
  const projects=(await call('/api/projects'+q,'GET',undefined,'owner')).data.projects;
  const project=projects.find(p=>p.clientEmail==='amelia@example.test');
  const invite=await call('/api/staff'+q,'POST',{email:'assistant-studio@example.test'},'owner');
  assert.equal(invite.status,201);
  assert.equal((await call('/api/staff-invitations/claim','POST',{token:new URL(invite.data.url).hash.slice(1),name:'Studio Assistant',password:'StudioAssistant2026!'},'staff')).status,200);
  const member=(await call('/api/staff'+q,'GET',undefined,'owner')).data.members[0];
  const route=`/api/staff/projects/${project.id}`,grant=`/api/staff/${member.id}/projects/${project.id}${q}`;
  assert.equal((await call(route+q,'GET',undefined,'staff')).status,404);
  assert.equal((await call(grant,'PATCH',{enabled:true},'client')).status,403);
  assert.equal((await call(grant,'PATCH',{enabled:true},'owner')).status,200);
  const visible=(await call('/api/projects'+q,'GET',undefined,'staff')).data.projects;
  assert.equal(visible.find(p=>p.id===project.id).canContribute,true);
  assert.equal(visible.filter(p=>p.canContribute).length,1);
  let response=await call(route+q,'GET',undefined,'staff');
  assert.equal(response.status,200);
  assert.equal(response.data.project.brief.budget,undefined);
  assert.equal(response.data.project.clientEmail,undefined);
  assert.equal(response.data.project.estimates,undefined);
  assert.equal(response.data.project.designs,undefined);
  assert.equal(response.data.project.messages.length,1);
  assert.equal((await call(route+'/brief'+q,'POST',{revision:0,brief:{vision:'Wrong revision'}},'staff')).status,409);
  response=await call(route+'/brief'+q,'POST',{revision:project.briefRevision,brief:{vision:'A revised calm celebration',budget:'999999'}},'staff');
  assert.equal(response.status,200);
  assert.equal(response.data.project.brief.vision,'A revised calm celebration');
  assert.equal(response.data.project.brief.budget,undefined);
  const ownerProject=(await call(`/api/projects/${project.id}${q}`,'GET',undefined,'owner')).data.project;
  assert.equal(ownerProject.brief.budget,'');
  response=await call(route+'/tasks'+q,'POST',{title:'Confirm delivery entrance',assignee:'studio',due:'2027-05-01'},'staff');
  assert.equal(response.status,200);
  const task=response.data.project.tasks.at(-1);
  assert.equal((await call(route+'/tasks'+q,'POST',{taskId:task.id,completed:true},'staff')).status,200);
  assert.equal((await call(route+'/references'+q,'POST',{title:'Atmosphere',note:'Soft candlelight'},'staff')).status,200);
  assert.equal((await call(route+'/messages'+q,'POST',{text:'I have updated the plan.',clientMessageId:'staff-message-1'},'staff')).status,200);
  const clientProject=(await call(`/api/projects/${project.id}${q}`,'GET',undefined,'client')).data.project;
  assert.ok(clientProject.messages.some(message=>message.text==='I have updated the plan.'));
  const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aF9kAAAAASUVORK5CYII=';
  const ownerAsset=(await call(`/api/projects/${project.id}/drafts/files${q}`,'POST',{name:'owner-only.png',content:png},'owner')).data.asset;
  const staffAsset=await call(route+'/drafts/files'+q,'POST',{name:'studio-direction.png',content:png},'staff');
  assert.equal(staffAsset.status,201);
  assert.equal((await call(route+'/drafts'+q,'POST',{title:'Wrong file',description:'No access',assetIds:[ownerAsset.fileId],briefRevision:project.briefRevision+1},'staff')).status,400);
  assert.equal((await call(`/api/projects/${project.id}/files/${staffAsset.data.asset.fileId}${q}`,'GET',undefined,'client')).status,404);
  const staffDraft=await call(route+'/drafts'+q,'POST',{title:'Soft arrival',description:'An opening scene with soft light.',assetIds:[staffAsset.data.asset.fileId],briefRevision:project.briefRevision+1},'staff');
  assert.equal(staffDraft.status,201);
  assert.equal(staffDraft.data.draft.createdByName,'Studio Assistant');
  assert.equal((await call(route+'/drafts'+q,'GET',undefined,'staff')).data.drafts.length,1);
  assert.equal((await call(route+'/drafts/'+staffDraft.data.draft.id+'/share'+q,'POST',{revision:staffDraft.data.draft.revision},'staff')).status,404);
  assert.equal((await call(`/api/projects/${project.id}/drafts${q}`,'GET',undefined,'client')).status,403);
  const ownerDrafts=(await call(`/api/projects/${project.id}/drafts${q}`,'GET',undefined,'owner')).data.drafts;
  assert.ok(ownerDrafts.some(draft=>draft.id===staffDraft.data.draft.id&&draft.createdByName==='Studio Assistant'));
  const shared=await call(`/api/projects/${project.id}/drafts/${staffDraft.data.draft.id}/share${q}`,'POST',{revision:staffDraft.data.draft.revision},'owner');
  assert.equal(shared.status,200);
  assert.equal(shared.data.project.designs.at(-1).title,'Soft arrival');
  assert.equal((await call(`/api/projects/${project.id}/files/${staffAsset.data.asset.fileId}${q}`,'GET',undefined,'client')).status,200);
  assert.equal((await call(`/api/projects/${project.id}/status${q}`,'POST',{status:'Complete'},'staff')).status,403);
  assert.equal((await call('/api/invoices'+q,'GET',undefined,'staff')).status,403);
  assert.equal((await call('/api/search'+q+'&q=amelia','GET',undefined,'staff')).status,403);
  assert.equal((await call(route+q,'GET',undefined,'client')).status,403);
  assert.equal((await call(grant,'PATCH',{enabled:false},'owner')).status,200);
  assert.equal((await call(route+q,'GET',undefined,'staff')).status,404);
  assert.equal((await call(route+'/messages'+q,'POST',{text:'Not allowed'},'staff')).status,404);
  assert.equal((await call(route+'/drafts'+q,'GET',undefined,'staff')).status,404);
  assert.equal((await call(route+'/drafts/files/'+staffAsset.data.asset.fileId+q,'GET',undefined,'staff')).status,404);
  assert.equal((await call('/api/projects'+q,'GET',undefined,'staff')).data.projects.find(p=>p.id===project.id).canContribute,false);
  assert.equal((await call(grant,'PATCH',{enabled:true},'owner')).status,200);
  assert.equal((await call(`/api/staff/${member.id}${q}`,'PATCH',{remove:true},'owner')).status,200);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM studio_project_collaborators').get().n,0);
  assert.equal((await call(route+q,'GET',undefined,'staff')).status,403);
 }finally{await new Promise(resolve=>server.close(resolve));db.close();await rm(dir,{recursive:true,force:true});}
});
