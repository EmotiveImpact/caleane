import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {createWorkspace} from '../server.mjs';
import {passwordHash} from '../store.mjs';

const origin='http://127.0.0.1:4320';

test('confirmed estimates produce tenant-safe invoices and owner-recorded external payments',async()=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'calenne-invoices-'));
 const dbFile=path.join(dir,'workspace.sqlite');
 let workspace=await createWorkspace({dbFile,origin,demo:true});
 await new Promise(resolve=>workspace.server.listen(0,'127.0.0.1',resolve));
 let base=`http://127.0.0.1:${workspace.server.address().port}`;
 const cookies={};
 async function call(route,method='GET',body,who=''){
  const response=await fetch(base+route,{method,headers:{Origin:origin,...(body?{'Content-Type':'application/json'}:{}),...(cookies[who]?{Cookie:cookies[who]}:{})},body:body?JSON.stringify(body):undefined});
  const cookie=response.headers.get('set-cookie');if(cookie&&who)cookies[who]=cookie.split(';')[0];
  return {status:response.status,data:await response.json()};
 }
 async function close(){await new Promise(resolve=>workspace.server.close(resolve));workspace.db.close();}
 try{
  assert.deepEqual((await call('/api/health')).data,{ok:true});
  assert.equal((await call('/api/login','POST',{email:'studio@example.test',password:'StudioDemo2026!'},'owner')).status,200);
  assert.equal((await call('/api/login','POST',{email:'amelia@example.test',password:'StudioDemo2026!'},'client')).status,200);
  const studio=(await call('/api/me','GET',undefined,'owner')).data.studios[0].id;
  const suffix=`?studio=${studio}`;
  const projects=(await call('/api/projects'+suffix,'GET',undefined,'owner')).data.projects;
  const project=projects.find(item=>item.clientEmail==='amelia@example.test');
  const other=projects.find(item=>item.id!==project.id);
  const route=`/api/projects/${project.id}/invoices`;
  const dueDate=new Date(Date.now()+14*86400000).toISOString().slice(0,10);
  const today=new Date().toISOString().slice(0,10);
  const issue={estimateId:'missing',kind:'Deposit',amountMinor:10000,dueDate,supplyDate:today,sellerAddress:'Studio Lane, London',sellerContact:'studio@example.test',customerAddress:'Client Street, London',taxRegistration:'',paymentInstructions:'Bank transfer to the studio using the invoice number.'};
  assert.equal((await call(route+suffix,'POST',issue,'owner')).status,409);
  assert.equal((await call(route+suffix,'POST',issue,'client')).status,403);
  assert.equal((await call('/api/invoices'+suffix,'GET',undefined,'client')).status,403);
  assert.deepEqual((await call(route+suffix,'GET',undefined,'client')).data.invoices,[]);
  const estimatePayload={title:'Project scope',currency:'GBP',items:[{title:'Creative direction',quantity:2,unitAmount:12550}],taxRate:20};
  let response=await call(`/api/projects/${project.id}/estimates${suffix}`,'POST',estimatePayload,'owner');
  assert.equal(response.status,200);
  const estimate=response.data.project.estimates.at(-1);
  response=await call(`/api/projects/${project.id}/estimate-decision${suffix}`,'POST',{estimateId:estimate.id,decision:'confirm'},'client');
  assert.equal(response.status,200);
  issue.estimateId=estimate.id;
  assert.equal((await call(route+suffix,'POST',{...issue,sellerAddress:''},'owner')).status,400);
  assert.equal((await call(route+suffix,'POST',{...issue,paymentInstructions:''},'owner')).status,400);
  assert.equal((await call(route+suffix,'POST',{...issue,amountMinor:estimate.total},'owner')).status,400);
  response=await call(route+suffix,'POST',issue,'owner');
  assert.equal(response.status,201);
  const deposit=response.data.invoice;
  assert.match(deposit.number,/^INV-\d{4}-0001$/);
  assert.equal(deposit.kind,'Deposit');
  assert.equal(deposit.amountMinor,10000);
  assert.equal(deposit.status,'Issued');
  assert.equal(deposit.snapshot.estimate.version,estimate.version);
  assert.equal(deposit.snapshot.estimate.total,estimate.total);
  assert.equal(deposit.snapshot.billToEmail,project.clientEmail);
  assert.equal(deposit.snapshot.sellerAddress,issue.sellerAddress);
  assert.equal(deposit.snapshot.customerAddress,issue.customerAddress);
  assert.equal(deposit.snapshot.supplyDate,issue.supplyDate);
  assert.equal((await call(`/api/projects/${project.id}${suffix}`,'GET',undefined,'client')).data.project.latestInvoice.number,deposit.number);
  for(const role of ['Viewer','Collaborator']){
   const email=`${role.toLowerCase()}-invoice@example.test`,userId=randomUUID(),contactId=randomUUID(),at=new Date().toISOString();
   workspace.db.prepare('INSERT INTO users VALUES(?,?,?,?)').run(userId,email,role,passwordHash('Participant2026!'));
   workspace.db.prepare('INSERT INTO memberships VALUES(?,?,?)').run(userId,studio,'client');
   workspace.db.prepare('INSERT INTO crm_contacts(id,studio_id,name,email,user_id,created_at,updated_at) VALUES(?,?,?,?,?,?,?)').run(contactId,studio,role,email,userId,at,at);
   workspace.db.prepare("INSERT INTO crm_client_contacts(studio_id,client_id,contact_id,role,primary_contact,account_access) VALUES(?,?,?,'Contact',0,1)").run(studio,project.clientId,contactId);
   workspace.db.prepare('INSERT INTO crm_project_stakeholders VALUES(?,?,?,?,1,0)').run(project.id,studio,contactId,role);
   const who=role.toLowerCase();assert.equal((await call('/api/login','POST',{email,password:'Participant2026!'},who)).status,200);
   assert.equal((await call(`/api/projects/${project.id}${suffix}`,'GET',undefined,who)).data.project.latestInvoice,null);
   assert.equal((await call(route+suffix,'GET',undefined,who)).status,403);
   assert.equal((await call(`${route}/${deposit.id}${suffix}`,'GET',undefined,who)).status,403);
  }
  assert.equal((await call(`/api/projects/${other.id}/invoices/${deposit.id}${suffix}`,'GET',undefined,'owner')).status,404);
  assert.equal((await call(`/api/projects/${other.id}/invoices${suffix}`,'GET',undefined,'client')).status,404);
  assert.equal((await call(`${route}/${deposit.id}/payments${suffix}`,'POST',{amountMinor:100,method:'bank_transfer',receivedAt:today},'client')).status,403);
  assert.equal((await call(`${route}/${deposit.id}/payments${suffix}`,'POST',{amountMinor:10001,method:'bank_transfer',receivedAt:today},'owner')).status,409);
  const payment={amountMinor:5000,method:'bank_transfer',receivedAt:today,reference:'BANK-123',clientPaymentId:'payment-key-one'};
  response=await call(`${route}/${deposit.id}/payments${suffix}`,'POST',payment,'owner');
  assert.equal(response.status,200);
  assert.equal(response.data.invoice.status,'Partially paid');
  assert.equal(response.data.invoice.paidMinor,5000);
  assert.equal(response.data.invoice.payments[0].source,'owner_recorded');
  assert.equal(response.data.invoice.payments[0].recordedBy,'NAY Studio');
  assert.equal((await call(`${route}/${deposit.id}/payments${suffix}`,'POST',payment,'owner')).data.invoice.payments.length,1);
  assert.equal((await call(`${route}/${deposit.id}/payments${suffix}`,'POST',{...payment,amountMinor:4000},'owner')).status,409);
  assert.equal((await call(`${route}/${deposit.id}/cancel${suffix}`,'POST',{reason:'Wrong estimate'},'owner')).status,409);
  assert.equal((await call(route+suffix,'POST',{...issue,kind:'Full'},'owner')).status,409);
  response=await call(route+suffix,'POST',{...issue,kind:'Balance',paymentInstructions:'Use the invoice number as your bank reference.'},'owner');
  assert.equal(response.status,201);
  const balance=response.data.invoice;
  assert.equal(balance.amountMinor,estimate.total-deposit.amountMinor);
  assert.match(balance.number,/^INV-\d{4}-0002$/);
  assert.equal((await call(route+suffix,'POST',{...issue,amountMinor:100},'owner')).status,409);
  assert.equal((await call(`${route}/${balance.id}/cancel${suffix}`,'POST',{reason:''},'owner')).status,400);
  response=await call(`${route}/${balance.id}/cancel${suffix}`,'POST',{reason:'Replacing payment terms'},'owner');
  assert.equal(response.data.invoice.status,'Cancelled');
  assert.equal(response.data.invoice.cancelReason,'Replacing payment terms');
  assert.equal((await call(`/api/projects/${project.id}${suffix}`,'GET',undefined,'owner')).data.project.latestInvoice.id,deposit.id);
  assert.equal((await call(`${route}/${balance.id}/payments${suffix}`,'POST',{amountMinor:100,method:'bank_transfer',receivedAt:today},'owner')).status,409);
  response=await call(`${route}/${deposit.id}/payments${suffix}`,'POST',{amountMinor:5000,method:'paypal_external',receivedAt:today,reference:'PP-456'},'owner');
  assert.equal(response.data.invoice.status,'Paid');
  response=await call(route+suffix,'POST',{...issue,kind:'Balance',paymentInstructions:'Updated instructions.'},'owner');
  assert.equal(response.status,201);
  assert.match(response.data.invoice.number,/^INV-\d{4}-0003$/);
  assert.equal(response.data.invoice.amountMinor,estimate.total-deposit.amountMinor);
  assert.equal((await call('/api/invoices'+suffix,'GET',undefined,'owner')).data.invoices.length,3);
  const clientInvoices=(await call(route+suffix,'GET',undefined,'client')).data.invoices;
  assert.equal(clientInvoices.length,3);
  assert.equal(clientInvoices.find(item=>item.id===deposit.id).status,'Paid');
  response=await call(`/api/projects/${project.id}/estimates${suffix}`,'POST',{...estimatePayload,title:'Revised scope',items:[{title:'Creative direction',quantity:2,unitAmount:20000}]},'owner');
  const revisedEstimate=response.data.project.estimates.at(-1);
  assert.equal((await call(`/api/projects/${project.id}/estimate-decision${suffix}`,'POST',{estimateId:revisedEstimate.id,decision:'confirm'},'client')).status,200);
  assert.equal((await call(route+suffix,'POST',{...issue,estimateId:revisedEstimate.id,kind:'Deposit',amountMinor:5000},'owner')).status,409);
  assert.equal((await call('/api/signup','POST',{name:'Other Owner',email:'other-invoices@example.test',studio:'Other Studio',slug:'other-invoices',password:'OtherStudio2026!'},'other')).status,201);
  const otherStudio=(await call('/api/me','GET',undefined,'other')).data.studios[0].id;
  assert.equal((await call(`/api/projects/${project.id}/invoices?studio=${otherStudio}`,'GET',undefined,'other')).status,404);
  assert.deepEqual((await call(`/api/invoices?studio=${otherStudio}`,'GET',undefined,'other')).data.invoices,[]);
  await close();
  workspace=await createWorkspace({dbFile,origin,demo:true});
  await new Promise(resolve=>workspace.server.listen(0,'127.0.0.1',resolve));
  base=`http://127.0.0.1:${workspace.server.address().port}`;
  response=await call(route+suffix,'GET',undefined,'client');
  assert.equal(response.status,200);
  assert.equal(response.data.invoices.length,3);
  assert.equal(response.data.invoices.find(item=>item.id===deposit.id).paidMinor,10000);
 }finally{
  if(workspace.server.listening)await close();
  await rm(dir,{recursive:true,force:true});
 }
});
